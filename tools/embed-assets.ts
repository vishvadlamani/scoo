// Bakes SvelteKit's client files into the Worker itself, so a deploy uploads one script and no
// static assets.
//
// Why: Cloudflare's static-asset upload authenticates with a short-lived JWT of its own, and the
// proxy this project deploys through replaces every Authorization header with the account token,
// so that upload fails with 401. The site's client files are small (JS, CSS, SVG), so serving them
// from the Worker costs nothing that matters, and the adapter's own Worker keeps working: it reads
// assets through `env.ASSETS.fetch`, which this replaces with a lookup in the embedded table.
//
// Runs after `vite build`, against the adapter's output in .svelte-kit/cloudflare.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';

const out = '.svelte-kit/cloudflare';
const client = join(out, 'client');
const workerDir = join(out, 'worker');

const TYPES: Record<string, string> = {
	'.js': 'text/javascript; charset=utf-8',
	'.css': 'text/css; charset=utf-8',
	'.html': 'text/html; charset=utf-8',
	'.json': 'application/json',
	'.svg': 'image/svg+xml',
	'.txt': 'text/plain; charset=utf-8',
	'.png': 'image/png',
	'.ico': 'image/x-icon',
	'.webp': 'image/webp',
	'.woff2': 'font/woff2'
};
const TEXT = new Set(['.js', '.css', '.html', '.json', '.svg', '.txt']);
// Files the adapter writes for the asset service that mean nothing to a Worker.
const SKIP = new Set(['_headers', '_redirects', '.assetsignore']);

function walk(dir: string): string[] {
	return readdirSync(dir).flatMap((name) => {
		const path = join(dir, name);
		return statSync(path).isDirectory() ? walk(path) : [path];
	});
}

type Entry = { type: string; text?: string; b64?: string };
const table: Record<string, Entry> = {};
let bytes = 0;
for (const file of walk(client)) {
	const rel = '/' + relative(client, file).split('\\').join('/');
	if (SKIP.has(rel.slice(1))) continue;
	const ext = extname(file).toLowerCase();
	const type = TYPES[ext];
	if (!type) throw new Error(`embed-assets: no content type for ${rel}; add one to TYPES`);
	const data = readFileSync(file);
	bytes += data.length;
	table[rel] = TEXT.has(ext) ? { type, text: data.toString('utf8') } : { type, b64: data.toString('base64') };
}

writeFileSync(
	join(workerDir, 'embedded.js'),
	`// Generated by tools/embed-assets.ts. Do not edit.
const table = ${JSON.stringify(table)};
const decoded = new Map();
function body(path, e) {
	if (e.text !== undefined) return e.text;
	let b = decoded.get(path);
	if (!b) { b = Uint8Array.from(atob(e.b64), (c) => c.charCodeAt(0)); decoded.set(path, b); }
	return b;
}
export const ASSETS = {
	async fetch(input) {
		const url = new URL(typeof input === 'string' ? input : input.url);
		let path = url.pathname;
		let e = table[path];
		if (!e && table[path.replace(/\\/$/, '') + '/index.html']) { path = path.replace(/\\/$/, '') + '/index.html'; e = table[path]; }
		if (!e && table[path + '.html']) { path = path + '.html'; e = table[path]; }
		if (!e) return new Response('Not found', { status: 404 });
		const headers = { 'content-type': e.type };
		headers['cache-control'] = path.includes('/immutable/') ? 'public, max-age=31536000, immutable' : 'public, max-age=300';
		return new Response(body(path, e), { headers });
	}
};
`
);

// Point the adapter's Worker at the embedded table instead of the asset binding.
const entry = join(workerDir, 'index.js');
let src = readFileSync(entry, 'utf8');
const uses = src.match(/env\.ASSETS\.fetch/g)?.length ?? 0;
if (uses === 0) throw new Error('embed-assets: env.ASSETS.fetch not found in the adapter Worker; the adapter changed');
src = `import { ASSETS as __EMBEDDED } from './embedded.js';\n` + src.replaceAll('env.ASSETS.fetch', '__EMBEDDED.fetch');
writeFileSync(entry, src);

// A front door ahead of SvelteKit. Prerendered pages and client files are answered before
// SvelteKit's hooks run, so a redirect that must cover every path lives here.
writeFileSync(
	join(workerDir, 'entry.js'),
	`// Generated by tools/embed-assets.ts. Do not edit.
import app from './index.js';
export default {
	fetch(req, env, ctx) {
		const url = new URL(req.url);
		// One canonical address: www.scoo.app sends people to scoo.app, keeping the path and query.
		if (url.hostname === 'www.scoo.app') {
			url.hostname = 'scoo.app';
			return Response.redirect(url.toString(), 301);
		}
		return app.fetch(req, env, ctx);
	}
};
`
);

// The deploy config: the front door as the entry, and no assets section.
const cfgPath = join(workerDir, 'wrangler.json');
const cfg = JSON.parse(readFileSync(cfgPath, 'utf8'));
delete cfg.assets;
cfg.main = 'entry.js';
writeFileSync(cfgPath, JSON.stringify(cfg, null, 2));

console.log(`embed-assets: ${Object.keys(table).length} files, ${(bytes / 1024).toFixed(0)} KB, ${uses} reads redirected`);

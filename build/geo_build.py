# Builds src/zips.js (ZIP -> "City, ST" and centroid) and src/areas.js (an outline, centre and
# name for every launch area) from GeoNames' US postal codes (CC BY 4.0).
#   python3 build/geo_build.py path/to/US.zip
import sys, zipfile, json, math, collections
src = sys.argv[1]
metros = json.load(open('src/metros.json'))
prefix_metro = {p: name for name, ps in metros for p in ps}

rows = {}
for line in zipfile.ZipFile(src).read('US.txt').decode().splitlines():
    f = line.split('\t'); z, city, st = f[1], f[2], f[4]
    if len(z) == 5 and z.isdigit() and st and f[9] and f[10]:
        rows.setdefault(z, (city, st, float(f[9]), float(f[10])))
zs = sorted(rows)
places = sorted({f'{c}, {s}' for c, s, _, _ in rows.values()}); pidx = {p: i for i, p in enumerate(places)}
def b36(n):
    a = '0123456789abcdefghijklmnopqrstuvwxyz'; o = ''
    while True:
        n, r = divmod(n, 36); o = a[r] + o
        if not n: return o
idx = ','.join(b36(pidx[f'{rows[z][0]}, {rows[z][1]}']) for z in zs)
coords = ','.join(f'{round(rows[z][2]*100)}:{round(rows[z][3]*100)}' for z in zs)
open('src/zips.js', 'w').write(f'''// US ZIP code to "City, ST" and its centroid, from GeoNames (https://www.geonames.org/), CC BY 4.0.
// Generated by build/geo_build.py. {len(zs)} ZIPs in one sorted string (5 digits each); for each,
// an index (base 36) into the place list and a centroid in hundredths of a degree (~1 km).
const ZIPS = {json.dumps(''.join(zs))};
const IDX = {json.dumps(idx)}.split(',');
const PLACES = {json.dumps(places)};
const COORDS = {json.dumps(coords)};
let coordList = null;
function find(zip) {{
  let lo = 0, hi = ZIPS.length / 5 - 1;
  while (lo <= hi) {{
    const mid = (lo + hi) >> 1, z = ZIPS.substr(mid * 5, 5);
    if (z === zip) return mid;
    if (z < zip) lo = mid + 1; else hi = mid - 1;
  }}
  return -1;
}}
export function placeForZip(zip) {{ const i = find(zip); return i < 0 ? null : PLACES[parseInt(IDX[i], 36)]; }}
export function coordsForZip(zip) {{
  const i = find(zip); if (i < 0) return null;
  coordList ||= COORDS.split(',');
  const [la, lo] = coordList[i].split(':');
  return [la / 100, lo / 100];
}}
''')

# areas: a tracked metro, else a 3-digit prefix; outline = padded convex hull of its ZIP centroids
groups = collections.defaultdict(list)
for z in zs:
    p = z[:3]; m = prefix_metro.get(p)
    groups[m.lower().replace(' ', '-') if m else 'zip-' + p].append(z)
def hull(pts):
    pts = sorted(set(pts))
    if len(pts) < 3: return pts
    def cross(o, a, b): return (a[0]-o[0])*(b[1]-o[1]) - (a[1]-o[1])*(b[0]-o[0])
    lo, up = [], []
    for p in pts:
        while len(lo) >= 2 and cross(lo[-2], lo[-1], p) <= 0: lo.pop()
        lo.append(p)
    for p in reversed(pts):
        while len(up) >= 2 and cross(up[-2], up[-1], p) <= 0: up.pop()
        up.append(p)
    return lo[:-1] + up[:-1]
areas = {}
for key, members in groups.items():
    pts = [(rows[z][3], rows[z][2]) for z in members]  # lon, lat
    cx = sum(p[0] for p in pts) / len(pts); cy = sum(p[1] for p in pts) / len(pts)
    h = hull(pts)
    pad = 0.05  # degrees: keep a lone ZIP or a thin hull visible
    if len(h) < 3:
        h = [(cx + pad*1.3*math.cos(t), cy + pad*math.sin(t)) for t in [i*math.pi/6 for i in range(12)]]
    else:
        h = [(cx + (x-cx)*1.08 + math.copysign(pad*0.6, x-cx), cy + (y-cy)*1.08 + math.copysign(pad*0.5, y-cy)) for x, y in h]
    if key.startswith('zip-'):
        name = collections.Counter(rows[z][0] for z in members).most_common(1)[0][0]
    else:
        name = next(n for n, ps in metros if n.lower().replace(' ', '-') == key)
    areas[key] = {'n': name, 'c': [round(cx, 3), round(cy, 3)], 'h': [[round(x, 3), round(y, 3)] for x, y in h]}
open('src/areas.js', 'w').write('// Launch areas: name, centre [lon, lat] and outline. Generated by build/geo_build.py from GeoNames.\nexport const AREAS = ' + json.dumps(areas, separators=(',', ':')) + ';\n')
print(len(zs), 'zips,', len(areas), 'areas')
